# sshd_config content with the TunnelVault block (re)placed at the end
sshd_config_with_block() {
    local file="$1"
    awk '
        /^# === TUNNELVAULT-GATEWAY START ===/ { skip = 1; next }
        /^# === TUNNELVAULT-GATEWAY END ===/   { skip = 0; next }
        !skip { lines[++n] = $0 }
        END {
            while (n > 0 && lines[n] ~ /^[ \t]*$/) n--
            for (i = 1; i <= n; i++) print lines[i]
        }' "$file"
    echo ""
    render_sshd_block
}

# ─── nginx ───────────────────────────────────────────────────────
# Globals used: LE_LIVE_DIR, ACME_WEBROOT, NGINX_MARKER
_nginx_listen() {
    local port="$1" ssl="$2" ipv6="$3" http2_directive="$4" suffix=""
    if [[ "$ssl" == 1 ]]; then
        suffix=" ssl"
        [[ "$http2_directive" == 1 ]] || suffix+=" http2"
    fi
    echo "    listen ${port}${suffix};"
    if [[ "$ipv6" == 1 ]]; then echo "    listen [::]:${port}${suffix};"; fi
    if [[ "$ssl" == 1 && "$http2_directive" == 1 ]]; then echo "    http2 on;"; fi
}

_nginx_tls() {
    local cert_dir="$1"
    cat <<EOF
    ssl_certificate     ${cert_dir}/fullchain.pem;
    ssl_certificate_key ${cert_dir}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305;
    ssl_prefer_server_ciphers off;
    ssl_session_timeout 1d;
    ssl_session_cache shared:TunnelVaultTLS:10m;
    ssl_session_tickets off;
EOF
}

# Headers are set once per server block: a proxy_set_header inside a location
# would silently drop all inherited ones.
_nginx_proxy_headers() {
    cat <<'EOF'
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $remote_addr;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $tunnelvault_connection_upgrade;
EOF
}

_nginx_acme_location() {
    cat <<EOF
    location ^~ /.well-known/acme-challenge/ {
        root ${ACME_WEBROOT};
        default_type text/plain;
    }
EOF
}

_nginx_tunnel_location() {
    local proxy_port="$1"
    cat <<EOF
    # HTTP tunnels: streamed in both directions, WebSockets pass through
    client_max_body_size 100m;
    location / {
        proxy_pass http://127.0.0.1:${proxy_port};
        proxy_buffering off;
        proxy_request_buffering off;
        proxy_read_timeout 1h;
        proxy_send_timeout 1h;
    }
EOF
}

# render_nginx_conf MODE DOMAIN API_PORT PROXY_PORT WILDCARD_DIR IPV6(0|1) HTTP2_DIRECTIVE(0|1)
#   MODE=acme : HTTP only, serves ACME challenges for DOMAIN (before a certificate exists)
#   MODE=https: final configuration
render_nginx_conf() {
    local mode="$1" domain="$2" api_port="$3" proxy_port="$4" wildcard="$5" ipv6="$6" h2="$7"
    cat <<EOF
${NGINX_MARKER} (regenerated on --upgrade).
# Delete the line above to keep local changes; the installer then leaves this file alone.
# tunnelvault-domain: ${domain}
# tunnelvault-wildcard-cert: ${wildcard:-none}

map \$http_upgrade \$tunnelvault_connection_upgrade {
    default upgrade;
    ''      close;
}

EOF
    if [[ "$mode" == "acme" ]]; then
        cat <<EOF
# Temporary: only answers Let's Encrypt HTTP-01 challenges until the certificate exists
server {
$(_nginx_listen 80 0 "$ipv6" "$h2")
    server_name ${domain};
    server_tokens off;
$(_nginx_acme_location)
    location / {
        return 503;
    }
}
EOF
        return 0
    fi

    cat <<EOF
# HTTP: ACME challenges (renewals) and redirect to HTTPS
server {
$(_nginx_listen 80 0 "$ipv6" "$h2")
    server_name ${domain};
    server_tokens off;
$(_nginx_acme_location)
    location / {
        return 301 https://\$host\$request_uri;
    }
}

# Dashboard, API, device WebSocket (/ws) and web terminal (/ws/ssh)
server {
$(_nginx_listen 443 1 "$ipv6" "$h2")
    server_name ${domain};
    server_tokens off;
$(_nginx_tls "${LE_LIVE_DIR}/${domain}")

    client_max_body_size 2m;
$(_nginx_proxy_headers)

    location / {
        proxy_pass http://127.0.0.1:${api_port};
    }
    location ^~ /ws/ssh {
        proxy_pass http://127.0.0.1:${api_port};
        proxy_buffering off;
        proxy_read_timeout 1d;
        proxy_send_timeout 1d;
    }
    location ^~ /ws {
        proxy_pass http://127.0.0.1:${api_port};
        proxy_buffering off;
        proxy_read_timeout 1d;
        proxy_send_timeout 1d;
    }
}

EOF
    if [[ -n "$wildcard" ]]; then
        cat <<EOF
# HTTP tunnels on *.${domain}: redirect to HTTPS
server {
$(_nginx_listen 80 0 "$ipv6" "$h2")
    server_name *.${domain};
    server_tokens off;
    location / {
        return 301 https://\$host\$request_uri;
    }
}

# HTTP tunnels on *.${domain} (wildcard certificate: ${wildcard})
server {
$(_nginx_listen 443 1 "$ipv6" "$h2")
    server_name *.${domain};
    server_tokens off;
$(_nginx_tls "$wildcard")

$(_nginx_proxy_headers)
$(_nginx_tunnel_location "$proxy_port")
}
EOF
    else
        cat <<EOF
# HTTP tunnels on *.${domain} over plain HTTP (no wildcard certificate configured;
# obtain one via DNS-01 and re-run with --wildcard-cert DIR to enable HTTPS)
server {
$(_nginx_listen 80 0 "$ipv6" "$h2")
    server_name *.${domain};
    server_tokens off;
$(_nginx_proxy_headers)
$(_nginx_tunnel_location "$proxy_port")
}
EOF
    fi
}

# Is this nginx site file generated by us (current or v1 installer)?
nginx_conf_is_ours() {
    local file="$1"
    [[ -f "$file" ]] || return 1
    head -n 3 "$file" | grep -Fq -e "$NGINX_MARKER" -e "$NGINX_LEGACY_MARKER"
}

# Wildcard certificate directory recorded in our nginx file ("" when none)
nginx_conf_wildcard_dir() {
    local file="$1" dir
    [[ -f "$file" ]] || return 0
    dir="$(sed -n 's/^# tunnelvault-wildcard-cert: //p' "$file" | head -n 1)"
    if [[ "$dir" != "none" ]] && is_safe_path "$dir"; then echo "$dir"; fi
}

# The old (unsigned, git pull as root) updater of TunnelVault 1.x?
is_legacy_updater() {
    local file="$1"
    [[ -f "$file" ]] && grep -Eq '^SOURCE_DIR=|git pull origin|__SOURCE_DIR__' "$file"
}

