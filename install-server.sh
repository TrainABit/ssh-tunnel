# ─── Step 9: legacy SSH gateway ──────────────────────────────────
reload_sshd() {
    local unit
    for unit in ssh.service sshd.service; do
        if systemctl cat "$unit" >/dev/null 2>&1; then
            systemctl try-reload-or-restart "$unit" && return 0
        fi
    done
    warn "Could not reload sshd — reload it manually"
}

configure_sshd() {
    local sshd_bin
    sshd_bin="$(command -v sshd || true)"
    if [[ -z "$sshd_bin" && -x /usr/sbin/sshd ]]; then sshd_bin=/usr/sbin/sshd; fi
    if [[ -z "$sshd_bin" || ! -f "$SSHD_CONF" ]]; then
        warn "OpenSSH server not found — legacy SSH gateway not configured"
        return 0
    fi
    local new backup
    new="$(mktemp)"
    sshd_config_with_block "$SSHD_CONF" > "$new"
    if cmp -s "$new" "$SSHD_CONF"; then
        rm -f "$new"
        skipped "SSH gateway configuration unchanged"
    else
        backup="$(mktemp)"
        cp -p "$SSHD_CONF" "$backup"
        cat "$new" > "$SSHD_CONF"
        rm -f "$new"
        if "$sshd_bin" -t >/dev/null 2>&1; then
            rm -f "$backup"
            info "SSH gateway configuration updated (Match User gw-*)"
            reload_sshd
        else
            cat "$backup" > "$SSHD_CONF"
            rm -f "$backup"
            warn "sshd rejected the gateway configuration — ${SSHD_CONF} restored, legacy gateway disabled"
            return 0
        fi
    fi

    # Existing gateway users: router as login shell (sshd runs ForceCommand through
    # it; /bin/false never worked) and membership of the sudo group for the helper.
    local user shell count=0
    while IFS=: read -r user shell; do
        [[ "$user" =~ ^gw-[A-Za-z0-9]{1,29}$ ]] || continue
        [[ "$(id -u "$user")" != "0" ]] || continue
        if [[ "$shell" == "${INSTALL_DIR}/ssh_router.sh" ]] && id -nG "$user" 2>/dev/null | tr ' ' '\n' | grep -qx "$GW_GROUP"; then
            continue
        fi
        usermod --shell "${INSTALL_DIR}/ssh_router.sh" --append --groups "$GW_GROUP" "$user" && count=$((count + 1))
    done < <(getent passwd | awk -F: '$1 ~ /^gw-/ { print $1 ":" $7 }')
    if (( count > 0 )); then info "Updated ${count} existing gateway user(s)"; fi
}

# ─── Step 10: systemd units ──────────────────────────────────────
install_units() {
    if [[ -f "${SYSTEMD_DIR}/tunnelvault-api.service" ]]; then
        systemctl disable --now tunnelvault-api.service >/dev/null 2>&1 || true
        rm -f "${SYSTEMD_DIR}/tunnelvault-api.service"
        notice "Removed tunnelvault-api.service left behind by the deprecated gateway/setup.sh"
    fi
    render_service_unit "$NODE_BIN"      | write_file "${SYSTEMD_DIR}/${SERVICE_NAME}.service" 0644 root:root || true
    render_usermgr_path_unit             | write_file "${SYSTEMD_DIR}/${USERMGR_UNIT}.path" 0644 root:root || true
    render_usermgr_service_unit          | write_file "${SYSTEMD_DIR}/${USERMGR_UNIT}.service" 0644 root:root || true
    systemctl daemon-reload
    systemctl enable "${SERVICE_NAME}.service" >/dev/null 2>&1
    systemctl enable --now "${USERMGR_UNIT}.path" >/dev/null 2>&1 \
        || warn "Could not start ${USERMGR_UNIT}.path — gateway users requested by the API will not be created"
    info "Units installed: ${SERVICE_NAME}.service, ${USERMGR_UNIT}.path/.service"
}

start_service() {
    systemctl restart "${SERVICE_NAME}.service" || true
    local host _
    host="$(env_get "$ENV_FILE" BIND_HOST)"
    if [[ -z "$host" || "$host" == "0.0.0.0" || "$host" == "::" ]]; then host="127.0.0.1"; fi
    if [[ "$host" == *:* ]]; then host="[${host}]"; fi
    for _ in $(seq 1 30); do
        if curl -fsS --max-time 2 -o /dev/null "http://${host}:${API_PORT}/api/health" 2>/dev/null; then
            info "Service is running and healthy"
            return 0
        fi
        systemctl is-failed --quiet "${SERVICE_NAME}.service" && break
        sleep 1
    done
    START_FAILED=true
    warn "The service did not become healthy. Check: journalctl -u ${SERVICE_NAME} -n 50"
    journalctl -u "$SERVICE_NAME" -n 10 --no-pager 2>/dev/null | sed 's/^/    /' || true
}

# ─── Step 11: signed auto-updater ────────────────────────────────
remove_updater_units() {
    systemctl disable --now "${UPDATER_UNIT}.timer" >/dev/null 2>&1 || true
    rm -f "${SYSTEMD_DIR}/${UPDATER_UNIT}.timer" "${SYSTEMD_DIR}/${UPDATER_UNIT}.service" "$UPDATER_SCRIPT"
    systemctl daemon-reload
}

# The client's signed updater (not its old git-pull one) reads the same update.conf
client_updater_installed() {
    [[ -f "${SYSTEMD_DIR}/${CLIENT_UPDATER_UNIT}.timer" && -f "$CLIENT_UPDATER_SCRIPT" ]] \
        && grep -q 'tv-updater-common' "$CLIENT_UPDATER_SCRIPT" 2>/dev/null
}

# /etc/tunnelvault holds the updater's trust anchor: root-owned, not group/world-writable
# (the updater refuses anything else). 0755 so the backend can read update.conf; the
# client's secrets in there (client.env) are 0600 on their own.
prepare_conf_dir() {
    if [[ -L "$CONF_DIR" || ( -e "$CONF_DIR" && ! -d "$CONF_DIR" ) ]]; then
        warn "${CONF_DIR} is a symlink or not a directory — refusing to write the updater configuration there"
        return 1
    fi
    if [[ -L "$UPDATE_CONF" || -L "$INSTALLED_PUBKEY" ]]; then
        warn "${UPDATE_CONF} or ${INSTALLED_PUBKEY} is a symlink — refusing to use it"
        return 1
    fi
    mkdir -p "$CONF_DIR"
    chown root:root "$CONF_DIR"
    chmod 0755 "$CONF_DIR"
}

configure_updater() {
    local legacy=false installed_before=false shared=false action conf_enabled
    is_legacy_updater "$UPDATER_SCRIPT" && legacy=true
    conf_enabled="$(env_get "$UPDATE_CONF" ENABLED)"
    if ! $legacy && [[ -f "${SYSTEMD_DIR}/${UPDATER_UNIT}.timer" && -f "$UPDATER_SCRIPT" ]]; then
        installed_before=true
    fi
    client_updater_installed && shared=true

    if [[ "$AUTO_UPDATE" == "yes" ]]; then
        action="install"
    elif [[ "$AUTO_UPDATE" == "no" ]]; then
        action="disable"
    elif $UPGRADE && $installed_before; then
        action="install"          # keep the previous choice (also while paused with ENABLED=0)
    else
        action="none"
    fi

    if [[ "$action" == "install" ]]; then
        if [[ ! -f "${SCRIPT_DIR}/auto-update.sh" ]] || is_legacy_updater "${SCRIPT_DIR}/auto-update.sh"; then
            warn "This source tree has no signed updater (auto-update.sh) — auto-update not installed"
            action="none"
        fi
        resolve_pubkey_source
        if [[ -z "$PUBKEY_SOURCE" ]]; then
            warn "No release public key available — auto-update not installed"
            action="none"
        elif ! is_p256_pubkey "$PUBKEY_SOURCE"; then
            warn "${PUBKEY_SOURCE} is not an ECDSA P-256 public key — auto-update not installed"
            action="none"
        fi
        if [[ "$action" == "install" ]] && ! prepare_conf_dir; then action="none"; fi
    fi

    case "$action" in
        install)
            if [[ "$PUBKEY_SOURCE" != "$INSTALLED_PUBKEY" ]]; then
                if [[ -f "$INSTALLED_PUBKEY" && -z "$RELEASE_PUBKEY_ARG" ]]; then
                    : # never replace the trust anchor implicitly
                else
                    write_file "$INSTALLED_PUBKEY" 0644 root:root < "$PUBKEY_SOURCE" && info "Release public key installed at ${INSTALLED_PUBKEY}"
                fi
            fi
            chown root:root "$INSTALLED_PUBKEY"; chmod 0644 "$INSTALLED_PUBKEY"
            if [[ -f "${SCRIPT_DIR}/release-signing.pub" ]] && ! cmp -s "${SCRIPT_DIR}/release-signing.pub" "$INSTALLED_PUBKEY"; then
                notice "release-signing.pub of this package differs from ${INSTALLED_PUBKEY} (kept). Use --release-pubkey to replace it."
            fi
            if [[ -f "$UPDATE_CONF" ]]; then
                # keep ENABLED (unless --auto-update), UPDATE_REPO, PINNED_VERSION and SCHEDULE
                [[ "$AUTO_UPDATE" == "yes" ]] && env_set "$UPDATE_CONF" ENABLED 1
                env_ensure "$UPDATE_CONF" SCHEDULE "$DEFAULT_UPDATE_SCHEDULE" || true
                env_ensure "$UPDATE_CONF" UPDATE_REPO "$DEFAULT_UPDATE_REPO" || true
                env_ensure "$UPDATE_CONF" PINNED_VERSION "" || true
                env_ensure "$UPDATE_CONF" PUBKEY "$INSTALLED_PUBKEY" || true
                chown root:root "$UPDATE_CONF"; chmod 0644 "$UPDATE_CONF"
            else
                render_update_conf 1 | write_file "$UPDATE_CONF" 0644 root:root || true
            fi
            write_file "$UPDATER_SCRIPT" 0755 root:root < "${SCRIPT_DIR}/auto-update.sh" || true
            render_updater_service_unit | write_file "${SYSTEMD_DIR}/${UPDATER_UNIT}.service" 0644 root:root || true
            render_updater_timer_unit "$(env_get "$UPDATE_CONF" SCHEDULE)" \
                | write_file "${SYSTEMD_DIR}/${UPDATER_UNIT}.timer" 0644 root:root || true
            systemctl daemon-reload
            systemctl enable --now "${UPDATER_UNIT}.timer" >/dev/null 2>&1 || warn "Could not enable ${UPDATER_UNIT}.timer"
            if $legacy; then
                notice "The old unsigned git-pull updater was replaced by the signed release updater"
            fi
            local schedule
            schedule="$(env_get "$UPDATE_CONF" SCHEDULE)"
            is_valid_schedule "$schedule" || schedule="$DEFAULT_UPDATE_SCHEDULE"
            if is_enabled_value "$(env_get "$UPDATE_CONF" ENABLED)"; then
                UPDATER_STATE="enabled (signed releases, every ${schedule})"
                info "Signed auto-updater enabled (every ${schedule}; key ${INSTALLED_PUBKEY}; settings ${UPDATE_CONF})"
            else
                UPDATER_STATE="installed but paused (ENABLED=0 in ${UPDATE_CONF})"
                warn "Signed auto-updater installed but paused: ENABLED=0 in ${UPDATE_CONF} (kept). Resume with --upgrade --auto-update."
            fi
            ;;
        disable)
            remove_updater_units
            if [[ -f "$UPDATE_CONF" && ! -L "$UPDATE_CONF" ]]; then
                if $shared; then
                    notice "${UPDATE_CONF} is shared with the client auto-updater on this host — ENABLED left unchanged there"
                else
                    env_set "$UPDATE_CONF" ENABLED 0
                fi
            fi
            $legacy && notice "The old unsigned git-pull updater was removed"
            UPDATER_STATE="disabled"
            info "Auto-updater disabled"
            ;;
        none)
            if $legacy; then
                remove_updater_units
                warn "Removed the old auto-updater: it ran 'git pull' as root without any verification."
            elif [[ -f "${SYSTEMD_DIR}/${UPDATER_UNIT}.timer" && ! -f "$UPDATER_SCRIPT" ]]; then
                remove_updater_units
                notice "Removed an orphaned ${UPDATER_UNIT}.timer (${UPDATER_SCRIPT} was missing)"
            fi
            if [[ -f "${SYSTEMD_DIR}/${UPDATER_UNIT}.timer" ]] && ! $legacy; then
                UPDATER_STATE="installed (not changed by this run)"
            elif [[ "$AUTO_UPDATE" == "yes" || "$conf_enabled" != "0" ]]; then
                UPDATER_STATE="not installed"
                notice "Signed auto-updates are off. Enable with:"
                notice "  sudo bash install-server.sh --upgrade --auto-update --release-pubkey /path/to/release-signing.pub"
            else
                UPDATER_STATE="disabled"
                skipped "Auto-updater disabled (${UPDATE_CONF})"
            fi
            ;;
    esac
    if $shared && [[ "$action" == "install" ]]; then
        notice "${UPDATE_CONF} is shared with the client auto-updater on this host: ENABLED=0 pauses both,"
        notice "UPDATE_REPO, PINNED_VERSION and SCHEDULE apply to both (each keeps its own timer)."
    fi
}

# ─── Step 12: firewall ───────────────────────────────────────────
firewall_rules() {
    # "port/proto|comment" lines
    if [[ "$TLS_MODE" != "none" ]]; then
        echo "80/tcp|TunnelVault HTTP (ACME, redirects, HTTP tunnels)"
        echo "443/tcp|TunnelVault HTTPS"
    else
        echo "${API_PORT}/tcp|TunnelVault API + dashboard"
        echo "${PROXY_PORT}/tcp|TunnelVault HTTP tunnel proxy"
    fi
    echo "${TCP_PORT_MIN}:${TCP_PORT_MAX}/tcp|TunnelVault TCP tunnels"
}

ssh_ports() {
    local p
    {
        echo 22
        if command -v sshd >/dev/null 2>&1; then
            sshd -T 2>/dev/null | awk '$1 == "port" { print $2 }'
        fi
    } | while read -r p; do is_valid_port "$p" && echo "$p"; done | sort -un
}

configure_firewall() {
    local rules spec comment status
    rules="$(firewall_rules)"
    if $NO_FIREWALL; then
        skipped "Firewall (--no-firewall). Allow inbound: $(cut -d'|' -f1 <<< "$rules" | tr '\n' ' ')"
        return 0
    fi
    if systemctl is-active --quiet firewalld 2>/dev/null; then
        warn "firewalld is active — not touching it. Allow inbound: $(cut -d'|' -f1 <<< "$rules" | tr '\n' ' ')"
        return 0
    fi
    if ! command -v ufw >/dev/null 2>&1; then
        if $UPGRADE; then
            skipped "ufw not installed. Allow inbound: $(cut -d'|' -f1 <<< "$rules" | tr '\n' ' ')"
            return 0
        fi
        apt_install ufw
    fi
    status="$(ufw status 2>/dev/null | head -n 1 || true)"
    if [[ "$status" != "Status: active" ]]; then
        if $UPGRADE; then
            warn "ufw is inactive — not enabling it during an upgrade. Allow inbound: $(cut -d'|' -f1 <<< "$rules" | tr '\n' ' ')"
            return 0
        fi
        ufw default deny incoming >/dev/null
        ufw default allow outgoing >/dev/null
        local p
        for p in $(ssh_ports); do
            ufw allow "${p}/tcp" comment "SSH" >/dev/null
            info "Allowed ${p}/tcp (SSH)"
        done
    fi
    while IFS='|' read -r spec comment; do
        [[ -n "$spec" ]] || continue
        ufw allow "$spec" comment "$comment" >/dev/null
        info "Allowed ${spec} (${comment})"
    done <<< "$rules"
    if [[ "$status" != "Status: active" ]]; then
        ufw --force enable >/dev/null
        info "Firewall enabled (default: deny incoming)"
    else
        info "Firewall already active — existing rules kept"
    fi
    if [[ "$TLS_MODE" != "none" ]] && ufw status 2>/dev/null | grep -Eq "^(${API_PORT}|${PROXY_PORT})/tcp"; then
        notice "Ports ${API_PORT}/${PROXY_PORT} are still allowed from an older install; TunnelVault now listens on 127.0.0.1 only."
        notice "Remove with: ufw delete allow ${API_PORT}/tcp && ufw delete allow ${PROXY_PORT}/tcp"
    fi
}

# ─── Step 13: nginx + Let's Encrypt ──────────────────────────────
nginx_reload() {
    systemctl enable nginx >/dev/null 2>&1 || true
    if systemctl is-active --quiet nginx; then systemctl reload nginx; else systemctl restart nginx; fi
}

# install_nginx_conf CONTENT_FILE: install, test, roll back on failure
install_nginx_conf() {
    local content="$1" site_file backup="" ts
    site_file="$(nginx_site_file)"
    if [[ -f "$site_file" ]] && cmp -s "$content" "$site_file"; then
        if [[ "$site_file" == */sites-available/* && ! -e "${NGINX_DIR}/sites-enabled/tunnelvault" ]]; then
            ln -sfn "$site_file" "${NGINX_DIR}/sites-enabled/tunnelvault"
            nginx -t >/dev/null 2>&1 && nginx_reload
        fi
        return 0
    fi
    if [[ -f "$site_file" ]]; then
        ts="$(date -u '+%Y%m%d-%H%M%S')"
        mkdir -p "$BACKUP_DIR"; chmod 0700 "$BACKUP_DIR"
        backup="${BACKUP_DIR}/nginx-tunnelvault.${ts}.conf"
        cp -p "$site_file" "$backup"
    fi
    write_file "$site_file" 0644 root:root < "$content" || true
    if [[ "$site_file" == */sites-available/* ]]; then
        mkdir -p "${NGINX_DIR}/sites-enabled"
        ln -sfn "$site_file" "${NGINX_DIR}/sites-enabled/tunnelvault"
    fi
    if nginx -t >/dev/null 2>&1; then
        nginx_reload
        return 0
    fi
    nginx -t 2>&1 | tail -n 3 | sed 's/^/    /' >&2 || true
    if [[ -n "$backup" ]]; then
        cp -p "$backup" "$site_file"
    else
        rm -f "$site_file" "${NGINX_DIR}/sites-enabled/tunnelvault"
    fi
    return 1
}

configure_tls() {
    local site_file content ipv6=0 h2=0 ver cert="${LE_LIVE_DIR}/${DOMAIN}/fullchain.pem"
    site_file="$(nginx_site_file)"
    if [[ "$TLS_MODE" == "existing" && -f "$site_file" ]] && ! nginx_conf_is_ours "$site_file"; then
        skipped "nginx configuration was customised (marker removed) — left unchanged"
        return 0
    fi
    apt_install nginx certbot
    [[ -f /proc/net/if_inet6 ]] && ipv6=1
    ver="$(nginx -v 2>&1 | sed -n 's|.*nginx/\([0-9.]*\).*|\1|p')"
    if [[ -n "$ver" ]] && version_ge "$ver" "1.25.1"; then h2=1; fi

    mkdir -p "$ACME_WEBROOT"; chmod 0755 "$ACME_WEBROOT"
    render_deploy_hook | write_file "$DEPLOY_HOOK" 0755 root:root || true
    content="$(mktemp)"

    if [[ ! -f "$cert" ]]; then
        if [[ "$TLS_MODE" == "existing" ]]; then
            warn "No certificate for ${DOMAIN} yet — obtain it with:"
            warn "  sudo bash install-server.sh --upgrade --tls --domain ${DOMAIN} [--email you@example.com]"
            rm -f "$content"
            return 0
        fi
        render_nginx_conf acme "$DOMAIN" "$API_PORT" "$PROXY_PORT" "" "$ipv6" "$h2" > "$content"
        if ! install_nginx_conf "$content"; then
            rm -f "$content"; TLS_FAILED=true
            warn "nginx rejected the temporary ACME configuration"
            return 0
        fi
        info "nginx answers ACME challenges for ${DOMAIN}"
        local email_args=(--register-unsafely-without-email)
        [[ -n "$TLS_EMAIL" ]] && email_args=(--email "$TLS_EMAIL")
        echo "  ${DIM}Requesting a Let's Encrypt certificate for ${DOMAIN} (HTTP-01)...${NC}"
        if ! certbot certonly --webroot -w "$ACME_WEBROOT" -d "$DOMAIN" --cert-name "$DOMAIN" \
                --non-interactive --agree-tos --keep-until-expiring "${email_args[@]}" 2>&1 | tail -n 5 | sed 's/^/    /' \
            || [[ ! -f "$cert" ]]; then
            rm -f "$content"; TLS_FAILED=true
            warn "certbot could not obtain a certificate. Check that ${DOMAIN} resolves to this server and"
            warn "port 80 is reachable, then re-run: sudo bash install-server.sh --upgrade --tls --domain ${DOMAIN}"
            return 0
        fi
        info "Certificate obtained (renewed automatically by certbot; nginx reloads via ${DEPLOY_HOOK})"
    fi

    render_nginx_conf https "$DOMAIN" "$API_PORT" "$PROXY_PORT" "$WILDCARD_DIR" "$ipv6" "$h2" > "$content"
    if install_nginx_conf "$content"; then
        TLS_OK=true
        info "nginx serves https://${DOMAIN} (dashboard, API, /ws, /ws/ssh)"
        if [[ -n "$WILDCARD_DIR" ]]; then
            info "HTTP tunnels: https://<subdomain>.${DOMAIN}"
        else
            notice "HTTP tunnels: http://<subdomain>.${DOMAIN} (plain HTTP; add --wildcard-cert DIR for HTTPS)"
        fi
    else
        [[ "$TLS_MODE" == "new" ]] && TLS_FAILED=true
        warn "nginx rejected the generated configuration — previous configuration restored"
    fi
    rm -f "$content"
}

# ─── Summary ─────────────────────────────────────────────────────
print_summary() {
    local host status
    status="$(systemctl is-active "$SERVICE_NAME" 2>/dev/null || true)"
    host="$(hostname -I 2>/dev/null | awk '{ print $1 }')"
    host="${host:-<server-ip>}"
    echo ""
    if $UPGRADE; then
        echo "${BOLD}${GREEN}  TunnelVault ${SOURCE_VERSION} — upgrade finished${NC}"
    else
        echo "${BOLD}${GREEN}  TunnelVault ${SOURCE_VERSION} — installation finished${NC}"
    fi
    echo "  ────────────────────────────────────────────────────"
    if $TLS_OK; then
        echo "  Dashboard:       ${CYAN}https://${DOMAIN}${NC}"
        echo "  Device server:   ${CYAN}wss://${DOMAIN}${NC}"
    else
        echo "  Dashboard:       ${CYAN}http://${host}:${API_PORT}${NC}   ${RED}(plaintext)${NC}"
        echo "  Device server:   ${CYAN}ws://${host}:${API_PORT}${NC}"
    fi
    echo "  TCP tunnels:     ports ${TCP_PORT_MIN}-${TCP_PORT_MAX}"
    echo "  Service:         ${status:-unknown}"
    echo "  Auto-update:     ${UPDATER_STATE}"
    if [[ -f "${SYSTEMD_DIR}/${UPDATER_UNIT}.timer" && -f "$UPDATER_SCRIPT" ]] && ! is_legacy_updater "$UPDATER_SCRIPT"; then
        echo "                   settings ${UPDATE_CONF}, key ${INSTALLED_PUBKEY}"
        echo "                   logs: journalctl -u ${UPDATER_UNIT} and ${UPDATER_LOG}"
        echo "                   run now: sudo ${UPDATER_SCRIPT} [--dry-run]"
    fi
    echo "  Config:          ${ENV_FILE}"
    echo "  Database:        ${DB_PATH}"
    echo "  Logs:            journalctl -u ${SERVICE_NAME} -f   (${LOG_DIR}/)"
    echo "  Gateway logs:    journalctl -t tunnelvault-gateway -t ${USERMGR_UNIT}"
    if $GENERATED_AUTH_TOKEN; then
        echo ""
        echo "  ${BOLD}${YELLOW}Admin token (log in to the dashboard with it; stored in ${ENV_FILE}):${NC}"
        echo "  ${BOLD}${AUTH_TOKEN}${NC}"
    elif ! $UPGRADE; then
        echo "  Admin token:     the one given with --auth-token (stored in ${ENV_FILE})"
    fi
    if ! $TLS_OK; then
        print_plaintext_warning
    fi
    if $TLS_FAILED; then
        echo "  ${RED}TLS setup did not complete — see the warnings above.${NC}"
    fi
    if $START_FAILED; then
        echo "  ${RED}The service is not healthy — see: journalctl -u ${SERVICE_NAME} -n 50${NC}"
    fi
    echo ""
}

# ================================================================
main() {
    parse_args "$@"
    if $ENABLE_TLS || { $UPGRADE && nginx_conf_is_ours "$(nginx_site_file)"; }; then TOTAL_STEPS=14; fi

    echo ""
    echo "${BOLD}${CYAN}  TunnelVault Server Installer${NC}"
    if $UPGRADE; then echo "  ${YELLOW}Mode: upgrade${NC}"; else echo "  ${DIM}Mode: install${NC}"; fi

    step "Pre-flight checks"
    preflight
    if [[ "$TLS_MODE" == "none" ]]; then print_plaintext_warning; fi

    step "System packages"
    apt-get update -qq >/dev/null || warn "apt-get update reported errors"
    apt_install sqlite3 netcat-openbsd curl ca-certificates gnupg openssl sudo util-linux

    step "Node.js (>= ${MIN_NODE_MAJOR})"
    ensure_node

    step "Service user and groups"
    ensure_users

    step "Preparing application (staging)"
    prepare_application

    step "Installing application files"
    if $UPGRADE && systemctl is-active --quiet "${SERVICE_NAME}.service"; then
        systemctl stop "${SERVICE_NAME}.service"
        info "Service stopped for the upgrade"
    fi
    swap_in_application
    install_gateway_files

    step "Configuration"
    configure_env

    step "Database"
    prepare_data_dirs
    init_database

    step "Legacy SSH gateway"
    configure_sshd

    step "systemd units"
    install_units

    step "Starting TunnelVault"
    start_service

    step "Signed auto-updates"
    configure_updater

    step "Firewall"
    configure_firewall

    if [[ "$TLS_MODE" != "none" ]]; then
        step "nginx + Let's Encrypt"
        configure_tls
    fi

    print_summary
    if $START_FAILED || $TLS_FAILED; then exit 1; fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main "$@"
fi
