# write_file DEST MODE OWNER < content — atomic replace (running scripts keep
# their old inode), returns 0 when the content changed.
write_file() {
    local dest="$1" mode="$2" owner="$3" tmp dir
    dir="$(dirname "$dest")"
    mkdir -p "$dir"
    tmp="$(mktemp "${dir}/.$(basename "$dest").XXXXXX")"
    cat > "$tmp"
    chmod "$mode" "$tmp"
    chown "$owner" "$tmp"
    if [[ -f "$dest" && ! -L "$dest" ]] && cmp -s "$tmp" "$dest"; then
        chmod "$mode" "$dest"; chown "$owner" "$dest"
        rm -f "$tmp"
        return 1
    fi
    mv -f "$tmp" "$dest"
    return 0
}

# chown only regular files/dirs that are not symlinks and not hard-linked
# (the data directory is writable by the service user).
safe_chown() {
    local owner="$1" path="$2"
    [[ -e "$path" && ! -L "$path" ]] || return 0
    if [[ -f "$path" && "$(stat -c %h "$path")" != "1" ]]; then
        warn "Not changing owner of hard-linked file ${path}"
        return 0
    fi
    chown "$owner" "$path"
}

apt_install() {
    local missing=() pkg
    for pkg in "$@"; do
        if dpkg -s "$pkg" >/dev/null 2>&1; then skipped "$pkg already installed"; else missing+=("$pkg"); fi
    done
    (( ${#missing[@]} )) || return 0
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${missing[@]}" >/dev/null
    info "Installed: ${missing[*]}"
}

confirm() {
    local prompt="$1" answer
    $ASSUME_YES && return 0
    read -r -p "  ${prompt} [y/N] " answer || return 1
    [[ "${answer,,}" == "y" || "${answer,,}" == "yes" ]]
}

