is_valid_port() { [[ "${1:-}" =~ ^[1-9][0-9]{0,4}$ ]] && (( $1 <= 65535 )); }

# Hostname with at least two labels (letters, digits, hyphens)
is_valid_domain() {
    local d="${1:-}"
    (( ${#d} <= 253 )) || return 1
    [[ "$d" =~ ^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$ ]]
}

# Publicly resolvable name suitable for Let's Encrypt (not an IP, not .local etc.)
is_public_domain() {
    local d="${1,,}"
    is_valid_domain "$d" || return 1
    [[ ! "$d" =~ ^[0-9.]+$ ]] || return 1
    case "$d" in
        *.local | *.localhost | localhost | *.internal | *.lan | *.home.arpa | *.test | *.invalid | *.example) return 1 ;;
    esac
    [[ "${d##*.}" =~ ^[a-z][a-z0-9-]*[a-z0-9]$ ]]
}

is_valid_email() {
    local re='^[A-Za-z0-9.!#%&*+/=?^_{|}~-]{1,64}@[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$'
    [[ "${1:-}" =~ $re && "$1" == *@*.* ]]
}

is_valid_auth_token() { [[ "${1:-}" =~ ^[A-Za-z0-9._~-]{16,256}$ ]]; }

# update.conf SCHEDULE -> systemd OnUnitActiveSec (same rule as install-client.sh)
is_valid_schedule() { [[ "${1:-}" =~ ^[1-9][0-9]{0,4}(min|h|d)$ ]]; }

# ENABLED semantics of the updater (auto-update.sh read_conf): 1/true/yes/on
is_enabled_value() { [[ "${1,,}" =~ ^(1|true|yes|on)$ ]]; }

# PEM ECDSA P-256 public key — the only key type the updaters accept (tv_check_pubkey)
is_p256_pubkey() {
    local text
    [[ -f "${1:-}" && -r "$1" ]] || return 1
    text="$(openssl pkey -pubin -in "$1" -noout -text 2>/dev/null)" || return 1
    [[ "$text" == *prime256v1* || "$text" == *P-256* ]]
}

# Absolute path without spaces or characters that are special in nginx/systemd files
is_safe_path() { [[ "${1:-}" =~ ^/[A-Za-z0-9._@+/-]*$ && "$1" != *..* ]]; }

# "v22.3.0" | "22.3.0" -> 22
version_major() { local v="${1#v}"; v="${v%%.*}"; [[ "$v" =~ ^[0-9]+$ ]] && echo "$v"; }

# version_ge A B: true when dotted version A >= B
version_ge() {
    local IFS=.
    local -a a b
    read -r -a a <<< "${1}"
    read -r -a b <<< "${2}"
    local i x y
    for i in 0 1 2 3; do
        x="${a[i]:-0}"; y="${b[i]:-0}"
        x="${x%%[!0-9]*}"; y="${y%%[!0-9]*}"
        x=$((10#${x:-0})); y=$((10#${y:-0}))
        (( x > y )) && return 0
        (( x < y )) && return 1
    done
    return 0
}

random_hex() { openssl rand -hex "${1:-32}"; }

# Value of KEY in an env file (last active assignment; surrounding quotes removed)
env_get() {
    local file="$1" key="$2"
    [[ -f "$file" ]] || return 0
    TV_KEY="$key" awk '
        BEGIN { k = ENVIRON["TV_KEY"]; re = "^[ \t]*(export[ \t]+)?" k "[ \t]*=" }
        $0 ~ re {
            v = $0; sub(/^[^=]*=/, "", v)
            sub(/^[ \t]+/, "", v); sub(/[ \t\r]+$/, "", v)
            q = substr(v, 1, 1)
            if (q != "\"" && q != "\047") sub(/[ \t]+#.*$/, "", v)
            if ((q == "\"" || q == "\047") && length(v) >= 2 && substr(v, length(v), 1) == q) v = substr(v, 2, length(v) - 2)
            val = v; found = 1
        }
        END { if (found) print val }' "$file"
}

# True when KEY has an active (uncommented) assignment
env_has() {
    local file="$1" key="$2"
    [[ -f "$file" ]] && grep -Eq "^[[:space:]]*(export[[:space:]]+)?${key}[[:space:]]*=" "$file"
}

# Set KEY=VALUE: replaces the first active assignment (drops duplicates) or appends.
# Rewrites in place so owner and mode of the file are kept.
env_set() {
    local file="$1" key="$2" value="$3" tmp
    [[ "$key" =~ ^[A-Z][A-Z0-9_]*$ ]] || { echo "env_set: bad key '$key'" >&2; return 1; }
    [[ "$value" != *$'\n'* && "$value" != *$'\r'* ]] || { echo "env_set: multi-line value for $key" >&2; return 1; }
    [[ -f "$file" ]] || : > "$file"
    tmp="$(mktemp "${file}.XXXXXX")"
    TV_KEY="$key" TV_VALUE="$value" awk '
        BEGIN { k = ENVIRON["TV_KEY"]; v = ENVIRON["TV_VALUE"]; re = "^[ \t]*(export[ \t]+)?" k "[ \t]*=" }
        $0 ~ re { if (!done) { print k "=" v; done = 1 } ; next }
        { print }
        END { if (!done) print k "=" v }' "$file" > "$tmp"
    cat "$tmp" > "$file"
    rm -f "$tmp"
}

# Append KEY=VALUE (with an optional comment line) only when KEY is not assigned yet.
# Returns 0 when it was added, 1 when it already existed.
env_ensure() {
    local file="$1" key="$2" value="$3" comment="${4:-}"
    env_has "$file" "$key" && return 1
    if [[ -s "$file" && -n "$(tail -c 1 "$file")" ]]; then echo >> "$file"; fi
    if [[ -n "$comment" ]]; then printf '# %s\n' "$comment" >> "$file"; fi
    env_set "$file" "$key" "$value"
    return 0
}

# Comment out TLS_CERT/TLS_KEY (and TLS_PROXY_*) lines that point into /etc/letsencrypt:
# the service user cannot read them (crash loop) and nginx terminates TLS instead.
# Prints the number of lines changed.
env_disable_letsencrypt_tls() {
    local file="$1" tmp count
    [[ -f "$file" ]] || { echo 0; return 0; }
    tmp="$(mktemp "${file}.XXXXXX")"
    count="$(awk -v out="$tmp" '
        BEGIN { re = "^[ \t]*(export[ \t]+)?TLS_(PROXY_)?(CERT|KEY)[ \t]*=[ \t]*[\"\047]?/etc/letsencrypt/" }
        {
            if ($0 ~ re) { print "# Disabled by install-server.sh (nginx terminates TLS): " $0 > out; n++ }
            else print $0 > out
        }
        END { print n + 0 }' "$file")"
    cat "$tmp" > "$file"
    rm -f "$tmp"
    echo "$count"
}

# Public URL template of HTTP tunnels behind nginx
http_tunnel_template() {
    local domain="$1" wildcard="$2"
    if [[ -n "$wildcard" ]]; then echo "https://{subdomain}.${domain}"; else echo "http://{subdomain}.${domain}"; fi
}

