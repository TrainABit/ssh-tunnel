_need_arg() { [[ $# -ge 2 && -n "$2" ]] || fail "Option $1 requires a value"; }

parse_args() {
    local need=_need_arg
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --domain)         $need "$@"; DOMAIN="${2,,}"; DOMAIN_SET=true; shift 2 ;;
            --auth-token)     $need "$@"; AUTH_TOKEN="$2"; AUTH_TOKEN_SET=true; shift 2 ;;
            --port)           $need "$@"; API_PORT="$2"; API_PORT_SET=true; shift 2 ;;
            --proxy-port)     $need "$@"; PROXY_PORT="$2"; PROXY_PORT_SET=true; shift 2 ;;
            --email)          $need "$@"; TLS_EMAIL="$2"; shift 2 ;;
            --wildcard-cert)  $need "$@"; WILDCARD_DIR="${2%/}"; shift 2 ;;
            --release-pubkey) $need "$@"; RELEASE_PUBKEY_ARG="$2"; shift 2 ;;
            --upgrade)        UPGRADE=true; shift ;;
            --tls)            ENABLE_TLS=true; shift ;;
            --no-firewall)    NO_FIREWALL=true; shift ;;
            --auto-update)    AUTO_UPDATE="yes"; shift ;;
            --no-auto-update) AUTO_UPDATE="no"; shift ;;
            -y|--yes)         ASSUME_YES=true; shift ;;
            -h|--help)        usage; exit 0 ;;
            *)                echo "Unknown option: $1 (see --help)" >&2; exit 1 ;;
        esac
    done

    if $DOMAIN_SET && ! is_valid_domain "$DOMAIN"; then fail "Invalid --domain '${DOMAIN}'"; fi
    if $AUTH_TOKEN_SET && ! is_valid_auth_token "$AUTH_TOKEN"; then
        fail "--auth-token must be 16-256 characters of A-Z a-z 0-9 . _ ~ -"
    fi
    is_valid_port "$API_PORT"   || fail "Invalid --port '${API_PORT}'"
    is_valid_port "$PROXY_PORT" || fail "Invalid --proxy-port '${PROXY_PORT}'"
    if [[ -n "$TLS_EMAIL" ]] && ! is_valid_email "$TLS_EMAIL"; then fail "Invalid --email '${TLS_EMAIL}'"; fi
    if [[ -n "$WILDCARD_DIR" ]]; then
        is_safe_path "$WILDCARD_DIR" || fail "--wildcard-cert must be an absolute path without spaces or special characters"
        $ENABLE_TLS || fail "--wildcard-cert requires --tls"
    fi
    if [[ -n "$TLS_EMAIL" ]] && ! $ENABLE_TLS; then fail "--email is only used with --tls"; fi
}

# ─── Step 1: pre-flight ──────────────────────────────────────────
preflight() {
    [[ $EUID -eq 0 ]] || fail "This script must be run as root. Use: sudo bash install-server.sh"
    info "Running as root"
    command -v apt-get >/dev/null 2>&1 || fail "This installer requires Debian/Ubuntu (apt-get not found)"
    command -v systemctl >/dev/null 2>&1 || fail "systemd is required"
    info "Debian/Ubuntu with systemd detected"

    local f
    for f in backend/src/server.js backend/src/database.js backend/package.json backend/package-lock.json \
             "${GATEWAY_SCRIPTS[@]/#/gateway/}" gateway/tunnelvault-sudoers; do
        [[ -f "${SCRIPT_DIR}/${f}" ]] || fail "Missing ${f} next to this script (${SCRIPT_DIR}). Run it from the project root."
    done
    if [[ -f "${SCRIPT_DIR}/VERSION" ]]; then
        local v
        v="$(tr -d '[:space:]' < "${SCRIPT_DIR}/VERSION")"
        if [[ "$v" =~ ^[0-9A-Za-z.+_-]{1,64}$ ]]; then SOURCE_VERSION="$v"; fi
    fi
    # A release package ships VERSION + a prebuilt dashboard and is not a git checkout
    # (a checkout may contain a stale local build, so it is always rebuilt).
    if [[ -f "${SCRIPT_DIR}/VERSION" && -f "${SCRIPT_DIR}/frontend/dist/index.html" && ! -e "${SCRIPT_DIR}/.git" ]]; then
        IS_RELEASE=true
        info "Release package ${SOURCE_VERSION} (prebuilt dashboard)"
    else
        info "Source tree at ${SCRIPT_DIR} (version: ${SOURCE_VERSION})"
    fi

    # Existing installation? The .env file belongs to the service user: never follow a
    # symlink or hard link there as root.
    if [[ -L "$ENV_FILE" ]] || { [[ -e "$ENV_FILE" ]] && { [[ ! -f "$ENV_FILE" ]] || [[ "$(stat -c %h "$ENV_FILE")" != "1" ]]; }; }; then
        fail "${ENV_FILE} is not a regular file (symlink or hard link?) — refusing to use it"
    fi
    if [[ -f "$ENV_FILE" ]]; then ENV_EXISTS=true; fi
    if $UPGRADE && [[ ! -d "${INSTALL_DIR}/backend" ]]; then
        warn "No existing installation found — performing a fresh install instead"
        UPGRADE=false
    fi
    if ! $UPGRADE && $ENV_EXISTS; then
        warn "Existing TunnelVault installation detected at ${INSTALL_DIR}"
        if $ASSUME_YES; then
            fail "Refusing to overwrite the existing configuration non-interactively. Use --upgrade."
        fi
        echo "  ${YELLOW}To upgrade without losing data, run: ${BOLD}sudo bash install-server.sh --upgrade${NC}"
        confirm "Continue with a fresh install? This REPLACES the configuration (a backup is kept)." \
            || { echo "  ${DIM}Aborted.${NC}"; exit 0; }
    fi
    if $UPGRADE; then
        info "Upgrade: database and configuration are preserved"
    fi

    # Values of an existing configuration (validated: the file is writable by the service user)
    if $ENV_EXISTS; then
        local v
        if ! $DOMAIN_SET; then
            v="$(env_get "$ENV_FILE" DOMAIN)"
            if [[ -n "$v" ]]; then
                is_valid_domain "$v" || fail "Invalid DOMAIN in ${ENV_FILE}"
                DOMAIN="${v,,}"
            fi
        fi
        if ! $API_PORT_SET; then
            v="$(env_get "$ENV_FILE" PORT)"
            if [[ -n "$v" ]]; then
                is_valid_port "$v" || fail "Invalid PORT in ${ENV_FILE}"
                API_PORT="$v"
            fi
        fi
        if ! $PROXY_PORT_SET; then
            v="$(env_get "$ENV_FILE" PROXY_PORT)"
            if [[ -n "$v" ]]; then
                is_valid_port "$v" || fail "Invalid PROXY_PORT in ${ENV_FILE}"
                PROXY_PORT="$v"
            fi
        fi
        v="$(env_get "$ENV_FILE" TCP_PORT_MIN)"; if is_valid_port "$v"; then TCP_PORT_MIN="$v"; fi
        v="$(env_get "$ENV_FILE" TCP_PORT_MAX)"; if is_valid_port "$v"; then TCP_PORT_MAX="$v"; fi
        v="$(env_get "$ENV_FILE" DB_PATH)"
        if [[ -n "$v" ]]; then
            if is_safe_path "$v" && [[ "$v" == "${DATA_DIR}/"* ]]; then
                DB_PATH="$v"
            else
                warn "DB_PATH=${v} is outside ${DATA_DIR}; the hardened service can only write to ${DATA_DIR}."
                warn "Using ${DEFAULT_DB_PATH} for initialisation — move the database or adjust the unit manually."
            fi
        fi
        if ! $UPGRADE; then
            # fresh install over an existing one: keep the encryption key of the kept database
            PREVIOUS_DATA_KEY="$(env_get "$ENV_FILE" DATA_ENCRYPTION_KEY)"
        fi
    fi
    (( TCP_PORT_MIN <= TCP_PORT_MAX )) || fail "TCP_PORT_MIN must not exceed TCP_PORT_MAX"
    [[ "$API_PORT" != "$PROXY_PORT" ]] || fail "--port and --proxy-port must differ"
    local p
    for p in "$API_PORT" "$PROXY_PORT"; do
        if (( p >= TCP_PORT_MIN && p <= TCP_PORT_MAX )); then
            fail "Port ${p} lies inside the TCP tunnel range ${TCP_PORT_MIN}-${TCP_PORT_MAX}"
        fi
    done

    # TLS mode
    local site_file
    site_file="$(nginx_site_file)"
    if $ENABLE_TLS; then
        TLS_MODE="new"
        if $UPGRADE && [[ -z "$WILDCARD_DIR" ]] && nginx_conf_is_ours "$site_file"; then
            WILDCARD_DIR="$(nginx_conf_wildcard_dir "$site_file")"
        fi
    elif $UPGRADE && nginx_conf_is_ours "$site_file"; then
        TLS_MODE="existing"
        WILDCARD_DIR="$(nginx_conf_wildcard_dir "$site_file")"
    fi
    if [[ "$TLS_MODE" != "none" ]]; then
        is_public_domain "$DOMAIN" \
            || fail "TLS needs a public domain name pointing to this server (got '${DOMAIN}'). Use --domain."
        if [[ -n "$WILDCARD_DIR" ]]; then
            [[ -f "${WILDCARD_DIR}/fullchain.pem" && -f "${WILDCARD_DIR}/privkey.pem" ]] \
                || fail "Wildcard certificate not found: ${WILDCARD_DIR}/fullchain.pem and privkey.pem are required"
            if command -v openssl >/dev/null 2>&1 \
                && ! openssl x509 -in "${WILDCARD_DIR}/fullchain.pem" -noout -text 2>/dev/null | grep -Fq "DNS:*.${DOMAIN}"; then
                warn "The certificate in ${WILDCARD_DIR} does not seem to cover *.${DOMAIN}"
            fi
        fi
        if [[ "$TLS_MODE" == "new" && -f "$site_file" ]] && ! nginx_conf_is_ours "$site_file"; then
            fail "${site_file} exists and was not created by this installer. Move it away and re-run."
        fi
        info "TLS: nginx terminates HTTPS for ${DOMAIN}"
    fi

    # Auto-update opt-in needs a public key
    if [[ "$AUTO_UPDATE" == "yes" ]]; then
        resolve_pubkey_source
        [[ -n "$PUBKEY_SOURCE" ]] \
            || fail "--auto-update needs the release public key: --release-pubkey FILE (or release-signing.pub next to this script)"
        [[ -f "${SCRIPT_DIR}/auto-update.sh" ]] || fail "auto-update.sh is missing next to this script"
        is_legacy_updater "${SCRIPT_DIR}/auto-update.sh" \
            && fail "${SCRIPT_DIR}/auto-update.sh is the old unsigned updater — use a current release"
    elif [[ -n "$RELEASE_PUBKEY_ARG" ]]; then
        resolve_pubkey_source
    fi
    if [[ -n "$PUBKEY_SOURCE" ]]; then
        is_p256_pubkey "$PUBKEY_SOURCE" \
            || fail "${PUBKEY_SOURCE} is not an ECDSA P-256 public key (PEM) — the updater only accepts P-256 release keys"
    fi
}

nginx_site_file() {
    if [[ -d "${NGINX_DIR}/sites-available" || ! -d "${NGINX_DIR}/conf.d" ]]; then
        echo "${NGINX_DIR}/sites-available/tunnelvault"
    else
        echo "${NGINX_DIR}/conf.d/tunnelvault.conf"
    fi
}

resolve_pubkey_source() {
    PUBKEY_SOURCE=""
    if [[ -n "$RELEASE_PUBKEY_ARG" ]]; then
        [[ -f "$RELEASE_PUBKEY_ARG" ]] || fail "Release public key not found: ${RELEASE_PUBKEY_ARG}"
        PUBKEY_SOURCE="$(cd "$(dirname "$RELEASE_PUBKEY_ARG")" && pwd)/$(basename "$RELEASE_PUBKEY_ARG")"
    elif [[ -f "$INSTALLED_PUBKEY" ]]; then
        PUBKEY_SOURCE="$INSTALLED_PUBKEY"
    elif [[ -f "${SCRIPT_DIR}/release-signing.pub" ]]; then
        PUBKEY_SOURCE="${SCRIPT_DIR}/release-signing.pub"
    fi
}

# ─── Step 3: Node.js ─────────────────────────────────────────────
ensure_node() {
    local major=""
    if command -v node >/dev/null 2>&1; then major="$(version_major "$(node -v 2>/dev/null)" || true)"; fi
    if [[ -n "$major" ]] && (( major >= MIN_NODE_MAJOR )); then
        info "Node.js $(node -v) found (>= ${MIN_NODE_MAJOR}) — keeping it"
    else
        if [[ -n "$major" ]]; then
            warn "Node.js $(node -v) is too old — upgrading to ${NODESOURCE_MAJOR}.x (NodeSource)"
        else
            info "Installing Node.js ${NODESOURCE_MAJOR}.x (NodeSource)"
        fi
        mkdir -p /etc/apt/keyrings
        curl -fsSL https://deb.nodesource.com/gpgkey/nodesource-repo.gpg.key \
            | gpg --dearmor --yes -o /etc/apt/keyrings/nodesource.gpg
        chmod 0644 /etc/apt/keyrings/nodesource.gpg
        echo "deb [signed-by=/etc/apt/keyrings/nodesource.gpg] https://deb.nodesource.com/node_${NODESOURCE_MAJOR}.x nodistro main" \
            > /etc/apt/sources.list.d/nodesource.list
        apt-get update -qq >/dev/null
        DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nodejs >/dev/null
        hash -r
        major="$(version_major "$(node -v 2>/dev/null)" || true)"
        if [[ -z "$major" ]] || (( major < MIN_NODE_MAJOR )); then fail "Node.js installation failed"; fi
        info "Node.js $(node -v) installed"
    fi
    command -v npm >/dev/null 2>&1 || fail "npm not found (it ships with the NodeSource nodejs package)"
    info "npm $(npm -v) available"
    NODE_BIN="$(command -v node)"
    case "$NODE_BIN" in
        /home/* | /root/* | /tmp/* | /var/tmp/* | /run/user/*)
            fail "node resolves to ${NODE_BIN}, which the hardened service cannot use. Install a system-wide Node.js >= ${MIN_NODE_MAJOR}." ;;
    esac
    is_safe_path "$NODE_BIN" || fail "Unsupported node path: ${NODE_BIN}"
}

# ─── Step 4: users ───────────────────────────────────────────────
ensure_users() {
    if id "$SERVICE_USER" >/dev/null 2>&1; then
        skipped "User '${SERVICE_USER}' already exists"
    else
        useradd --system --shell /usr/sbin/nologin --home-dir "$INSTALL_DIR" --no-create-home "$SERVICE_USER"
        info "System user '${SERVICE_USER}' created"
    fi
    if getent group "$GW_GROUP" >/dev/null 2>&1; then
        skipped "Group '${GW_GROUP}' already exists"
    else
        groupadd --system "$GW_GROUP"
        info "Group '${GW_GROUP}' created (legacy SSH gateway users)"
    fi
}

# ─── Step 5: build into a staging directory (the running install is untouched) ─
npm_ci_production() {
    (cd "$1" && npm ci --omit=dev --no-audit --no-fund --loglevel=error)
}

prepare_application() {
    mkdir -p "$INSTALL_DIR"
    chown root:root "$INSTALL_DIR"
    chmod 0755 "$INSTALL_DIR"
    STAGE_DIR="${INSTALL_DIR}/.staging"
    rm -rf "$STAGE_DIR"
    mkdir -p "${STAGE_DIR}/backend" "${STAGE_DIR}/frontend"

    cp -R "${SCRIPT_DIR}/backend/src" "${STAGE_DIR}/backend/src"
    cp "${SCRIPT_DIR}/backend/package.json" "${SCRIPT_DIR}/backend/package-lock.json" "${STAGE_DIR}/backend/"
    echo "  ${DIM}Installing backend dependencies (npm ci --omit=dev)...${NC}"
    if ! npm_ci_production "${STAGE_DIR}/backend"; then
        warn "npm ci failed — installing build tools for native modules and retrying"
        apt_install build-essential python3
        rm -rf "${STAGE_DIR}/backend/node_modules"
        npm_ci_production "${STAGE_DIR}/backend" || fail "npm ci failed — the running installation was not changed"
    fi
    (cd "${STAGE_DIR}/backend" && "$NODE_BIN" -e "require('better-sqlite3'); require('ws'); require('express')") \
        || fail "Backend dependencies are not loadable — the running installation was not changed"
    info "Backend prepared"

    FRONTEND_DIST_SRC=""
    if $IS_RELEASE; then
        FRONTEND_DIST_SRC="${SCRIPT_DIR}/frontend/dist"
        info "Using the prebuilt dashboard of the release"
    elif [[ "${TUNNELVAULT_UPDATER:-}" == 1 ]]; then
        # Unattended runs never execute the frontend toolchain's install scripts as root:
        # signed releases ship frontend/dist.
        warn "This package has no prebuilt dashboard (frontend/dist) — keeping the installed one"
    elif [[ -f "${SCRIPT_DIR}/frontend/package.json" ]]; then
        echo "  ${DIM}Building the dashboard (npm ci && npm run build)...${NC}"
        if (cd "${SCRIPT_DIR}/frontend" && npm ci --no-audit --no-fund --loglevel=error && npm run build --silent); then
            FRONTEND_DIST_SRC="${SCRIPT_DIR}/frontend/dist"
            info "Dashboard built"
        else
            warn "Dashboard build failed — keeping the currently installed dashboard (if any)"
        fi
    fi
    if [[ -n "$FRONTEND_DIST_SRC" && -f "${FRONTEND_DIST_SRC}/index.html" ]]; then
        cp -R "$FRONTEND_DIST_SRC" "${STAGE_DIR}/frontend/dist"
    else
        FRONTEND_DIST_SRC=""
        [[ -f "${INSTALL_DIR}/frontend/dist/index.html" ]] || warn "No dashboard build available — the dashboard UI will be missing"
    fi
}

# ─── Step 6: install files ───────────────────────────────────────
swap_in_application() {
    local trash="${INSTALL_DIR}/.previous" item
    rm -rf "$trash"
    mkdir -p "${trash}/backend" "${trash}/frontend" "${INSTALL_DIR}/backend" "${INSTALL_DIR}/frontend"
    for item in src node_modules package.json package-lock.json; do
        if [[ -e "${INSTALL_DIR}/backend/${item}" || -L "${INSTALL_DIR}/backend/${item}" ]]; then
            mv "${INSTALL_DIR}/backend/${item}" "${trash}/backend/${item}"
        fi
        mv "${STAGE_DIR}/backend/${item}" "${INSTALL_DIR}/backend/${item}"
    done
    if [[ -d "${STAGE_DIR}/frontend/dist" ]]; then
        if [[ -e "${INSTALL_DIR}/frontend/dist" ]]; then mv "${INSTALL_DIR}/frontend/dist" "${trash}/frontend/dist"; fi
        mv "${STAGE_DIR}/frontend/dist" "${INSTALL_DIR}/frontend/dist"
    fi
    rm -rf "$trash" "$STAGE_DIR"

    # Application code is root-owned and read-only for the service
    chown -R root:root "${INSTALL_DIR}/backend/src" "${INSTALL_DIR}/backend/node_modules" \
        "${INSTALL_DIR}/backend/package.json" "${INSTALL_DIR}/backend/package-lock.json" "${INSTALL_DIR}/frontend"
    chmod -R u=rwX,go=rX "${INSTALL_DIR}/backend/src" "${INSTALL_DIR}/backend/node_modules" "${INSTALL_DIR}/frontend"
    chmod 0644 "${INSTALL_DIR}/backend/package.json" "${INSTALL_DIR}/backend/package-lock.json"
    chown root:root "${INSTALL_DIR}/backend"
    chmod 0755 "${INSTALL_DIR}/backend" "${INSTALL_DIR}/frontend"
    printf '%s\n' "$SOURCE_VERSION" | write_file "$VERSION_FILE" 0644 root:root || true
    info "Application files installed (version ${SOURCE_VERSION})"
}

install_gateway_files() {
    local script
    for script in "${GATEWAY_SCRIPTS[@]}"; do
        write_file "${INSTALL_DIR}/${script}" 0755 root:root < "${SCRIPT_DIR}/gateway/${script}" || true
    done
    info "Gateway scripts installed: ${GATEWAY_SCRIPTS[*]}"

    # sudoers: validate before it goes live (a broken file would disable sudo)
    local tmp
    tmp="$(mktemp)"
    cat "${SCRIPT_DIR}/gateway/tunnelvault-sudoers" > "$tmp"
    if command -v visudo >/dev/null 2>&1 && ! visudo -c -q -f "$tmp" >/dev/null 2>&1; then
        rm -f "$tmp"
        fail "gateway/tunnelvault-sudoers failed validation (visudo -c)"
    fi
    mkdir -p "$(dirname "$SUDOERS_FILE")"
    write_file "$SUDOERS_FILE" 0440 root:root < "$tmp" || true
    rm -f "$tmp"
    info "Sudoers rule installed (${GW_GROUP} -> gateway-helper.sh as ${SERVICE_USER}; the service has no sudo rights)"

    render_logrotate | write_file "$LOGROTATE_FILE" 0644 root:root || true
}

# ─── Step 7: configuration ───────────────────────────────────────
configure_env() {
    local ts
    ts="$(date -u '+%Y%m%d-%H%M%S')"
    if $ENV_EXISTS; then
        mkdir -p "$BACKUP_DIR"; chmod 0700 "$BACKUP_DIR"
        cp -p "$ENV_FILE" "${BACKUP_DIR}/env.${ts}"
        chmod 0600 "${BACKUP_DIR}/env.${ts}"
        info "Previous configuration backed up to ${BACKUP_DIR}/env.${ts}"
    fi

    if $UPGRADE && $ENV_EXISTS; then
        info "Preserving existing configuration at ${ENV_FILE}"
        $DOMAIN_SET     && env_set "$ENV_FILE" DOMAIN "$DOMAIN"         && notice "DOMAIN set to ${DOMAIN}"
        $API_PORT_SET   && env_set "$ENV_FILE" PORT "$API_PORT"         && notice "PORT set to ${API_PORT}"
        $PROXY_PORT_SET && env_set "$ENV_FILE" PROXY_PORT "$PROXY_PORT" && notice "PROXY_PORT set to ${PROXY_PORT}"
        if $AUTH_TOKEN_SET; then
            env_set "$ENV_FILE" AUTH_TOKEN "$AUTH_TOKEN"
            notice "AUTH_TOKEN replaced (existing dashboard sessions are logged out)"
        fi
        env_ensure "$ENV_FILE" NODE_ENV production || true
        env_ensure "$ENV_FILE" DB_PATH "$DB_PATH" || true
        env_ensure "$ENV_FILE" USERMGR_SPOOL_DIR "$USERMGR_SPOOL_DIR" \
            "Legacy SSH gateway: Linux user requests are queued here (tunnelvault-usermgr.path)" \
            && info "USERMGR_SPOOL_DIR added"
        env_ensure "$ENV_FILE" GEOIP_PROVIDER off \
            "GeoIP for sessions: off | maxmind (GEOIP_DB=/path/GeoLite2-City.mmdb) | ip-api (non-commercial, plain HTTP)" \
            && notice "GEOIP_PROVIDER=off added (visitor IPs are no longer sent to ip-api.com)"
        env_ensure "$ENV_FILE" SESSION_RETENTION_DAYS 90 \
            "Delete connection sessions (visitor IPs) older than N days (0 = keep forever)" \
            && info "SESSION_RETENTION_DAYS=90 added"
        if [[ -z "$(env_get "$ENV_FILE" DATA_ENCRYPTION_KEY)" && -z "$(env_get "$ENV_FILE" DATA_ENCRYPTION_KEY_FILE)" ]]; then
            if env_has "$ENV_FILE" DATA_ENCRYPTION_KEY; then
                env_set "$ENV_FILE" DATA_ENCRYPTION_KEY "$(random_hex 32)"
            else
                env_ensure "$ENV_FILE" DATA_ENCRYPTION_KEY "$(random_hex 32)" \
                    "Encrypts SSH private keys stored for the web terminal (AES-256-GCM). Do not lose it." || true
            fi
            info "DATA_ENCRYPTION_KEY generated (stored SSH keys are encrypted at rest)"
        fi
    else
        if [[ -z "$AUTH_TOKEN" ]]; then
            AUTH_TOKEN="$(random_hex 32)"
            GENERATED_AUTH_TOKEN=true
            info "Admin token generated (64 hex characters)"
        else
            info "Using the provided admin token"
        fi
        local data_key
        if [[ -n "$PREVIOUS_DATA_KEY" && -f "$DB_PATH" ]]; then
            data_key="$PREVIOUS_DATA_KEY"
            notice "Keeping the previous DATA_ENCRYPTION_KEY (the existing database is kept)"
        else
            data_key="$(random_hex 32)"
        fi
        mkdir -p "$(dirname "$ENV_FILE")"
        local new_env
        new_env="$(mktemp "${ENV_FILE}.XXXXXX")"     # 0600, O_EXCL: never follows a planted link
        render_env_file "$data_key" > "$new_env"
        mv -f "$new_env" "$ENV_FILE"
        info "Configuration written to ${ENV_FILE}"
    fi

    # TLS-related settings
    if [[ "$TLS_MODE" != "none" ]]; then
        local n
        n="$(env_disable_letsencrypt_tls "$ENV_FILE")"
        if (( n > 0 )); then
            notice "Commented out ${n} TLS_CERT/TLS_KEY line(s) pointing into /etc/letsencrypt (nginx terminates TLS now)"
        fi
    fi
    if [[ "$TLS_MODE" == "new" ]]; then
        env_set "$ENV_FILE" BIND_HOST 127.0.0.1
        env_set "$ENV_FILE" TRUST_PROXY loopback
        env_set "$ENV_FILE" PUBLIC_URL "https://${DOMAIN}"
        env_set "$ENV_FILE" HTTP_TUNNEL_URL_TEMPLATE "$(http_tunnel_template "$DOMAIN" "$WILDCARD_DIR")"
        info "TLS settings: BIND_HOST=127.0.0.1, TRUST_PROXY=loopback, PUBLIC_URL=https://${DOMAIN}"
    elif [[ "$TLS_MODE" == "existing" ]]; then
        if [[ -f "${LE_LIVE_DIR}/${DOMAIN}/fullchain.pem" ]]; then
            env_ensure "$ENV_FILE" BIND_HOST 127.0.0.1 || true
            env_ensure "$ENV_FILE" TRUST_PROXY loopback || true
            env_ensure "$ENV_FILE" PUBLIC_URL "https://${DOMAIN}" || true
            env_ensure "$ENV_FILE" HTTP_TUNNEL_URL_TEMPLATE "$(http_tunnel_template "$DOMAIN" "$WILDCARD_DIR")" || true
        else
            warn "nginx is configured for ${DOMAIN} but no certificate exists yet."
            warn "Obtain it with: sudo bash install-server.sh --upgrade --tls --domain ${DOMAIN} [--email you@example.com]"
        fi
    fi

    chown "${SERVICE_USER}:${SERVICE_USER}" "$ENV_FILE"
    chmod 0600 "$ENV_FILE"
}

